#!/usr/bin/env python3
"""Writes tool/hadi_core/spec_96_knowledge_pack_k_layers.py from
assets/stories/layers/*.json, so Hadi can answer, in detail, what the app's
checked story layers hold: Qur'an passages, Sahih hadith, tafsir summaries and
where scholars differ. Only hadith graded exactly "Sahih" are used. Run from the
repo root:  python3 tool/hadi_core/gen/gen_layers.py
"""
import glob, json, os, re, sys

ORDER = ['adam', 'idris', 'nuh', 'hud', 'salih', 'ibrahim', 'lut', 'ismail', 'ishaq',
         'yaqub', 'yusuf', 'ayyub', 'shuayb', 'musa', 'harun', 'dawud', 'sulayman',
         'ilyas', 'alyasa', 'yunus', 'dhul-kifl', 'zakariya', 'isa', 'maryam',
         'angels', 'jinn']
NAMES = {
    'adam': ['adam'], 'idris': ['idris', 'enoch'], 'nuh': ['nuh', 'noah', 'nooh'],
    'hud': ['hud'], 'salih': ['salih', 'saleh'],
    'ibrahim': ['ibrahim', 'abraham', 'ibraheem'], 'lut': ['lut', 'lot', 'loot'],
    'ismail': ['ismail', 'ishmael', 'ismael'], 'ishaq': ['ishaq', 'isaac', 'ishak'],
    'yaqub': ['yaqub', 'jacob', 'yakub', 'yaqoob'],
    'yusuf': ['yusuf', 'joseph', 'yousuf'], 'ayyub': ['ayyub', 'job', 'ayub', 'ayoub'],
    'shuayb': ['shuayb', 'jethro', 'shuaib', 'shoaib'], 'musa': ['musa', 'moses', 'moosa'],
    'harun': ['harun', 'aaron', 'haroon'],
    'dawud': ['dawud', 'david', 'dawood', 'daud'],
    'sulayman': ['sulayman', 'solomon', 'suleiman', 'sulaiman'],
    'ilyas': ['ilyas', 'elijah', 'ilyaas'], 'alyasa': ['alyasa', 'elisha'],
    'yunus': ['yunus', 'jonah', 'younus'], 'dhul-kifl': ['dhul kifl', 'zulkifl', 'dhulkifl'],
    'zakariya': ['zakariya', 'zechariah', 'zakaria', 'zakariyya'],
    'isa': ['isa', 'jesus', 'eesa'], 'maryam': ['maryam', 'mary', 'mariam'],
    'angels': ['angels?', 'jibril', 'gabriel', 'israfil', 'mikail'],
    'jinn': ['jinn', 'jinns', 'djinn'],
}
RISKY_WORDS = {'job', 'lot', 'mary'}  # common English words: need a religious word too
CUE = (r'in detail|detailed|more detail|more about|deeper|tafsir|scholars?|differ\w*|'
       r'disagree\w*|hadiths?|sahih|sources?|evidence|what does the quran say|'
       r'quran say|ibn kathir|references?')
WORKS = {'Tafsir Ibn Kathir (abridged English edition, read on Quran.com)': 'Tafsir Ibn Kathir',
         'Ma’ariful Qur’an (English edition, read on Quran.com)': 'Ma’ariful Qur’an'}


def rx(words):
    return '(?:' + '|'.join(words) + ')'


def clean(s):
    s = s.replace('"""', '').replace('\\', '')
    return re.sub(r'\s+', ' ', s).strip()


def patterns(sub):
    safe = [w for w in NAMES[sub] if w not in RISKY_WORDS]
    risky = [w for w in NAMES[sub] if w in RISKY_WORDS]
    rel = r'(?=.*\b(?:prophet|nabi|quran|islam\w*|story|stories)\b)'
    pats = []
    for words, pre in ((safe, ''), (risky, rel)):
        if not words:
            continue
        n = rx(words)
        lead = r'^' + pre + r'.*' if pre else r'\b'
        pats.append(lead + r'\b(?:' + CUE + r')\b.*\b' + n + r'\b')
        pats.append(lead + r'\b' + n + r'\b.*\b(?:' + CUE + r')\b')
        if sub in ('angels', 'jinn'):
            pats.append(r'\b(?:what do you know about|tell me about|who are|what are|explain) (?:the )?' + n + r'\b')
    return [p.replace("'", '') for p in pats]


def other_summaries():
    seen = {}
    for f in glob.glob('tool/hadi_core/spec_96_*.py'):
        if f.endswith('k_layers.py'):
            continue
        for m in re.finditer(r'\{HS (\w+:\d+)\|', open(f, encoding='utf8').read()):
            seen[m.group(1)] = '(other pack)'
    return seen


WEAK = set(os.environ.get('HADI_WEAK', '').split(','))


def main():
    seen = other_summaries()
    out = ['# Knowledge pack K (21 Nov 2026): the app\'s checked story layers, in detail.',
           '# GENERATED by tool/hadi_core/gen/gen_layers.py from assets/stories/layers/*.json.',
           '# Edit the layer or the generator, not this file. Weak or disputed hadith are stated as such, never hidden.', '']
    for sub in ORDER:
        d = json.load(open(f'assets/stories/layers/{sub}.json', encoding='utf8'))
        title = clean(d['title'])
        parts = [f'{title}: what the app\'s checked sources hold, in detail.']
        q = []
        for r in d.get('quran', []):
            ref = f"{r['surah']}:{r['from']}" + (f"-{r['to']}" if r['to'] != r['from'] else '')
            # The checker wants any quotation beside a Qur'an reference to be the
            # bundled wording word for word; the notes paraphrase, so no quote marks.
            note = re.sub('[“”"]', '', clean(r['note']))
            q.append(f"{note} ({{QR {ref}}})")
        if q:
            parts.append('In the Qur\'an:\n' + '\n'.join('- ' + x for x in q))
        h = []
        for x in d.get('hadith', []):
            key = f"{x['book']}:{x['number']}"
            s = clean(x['summary'])
            if x['grade'] != 'Sahih':
                # Stated, never hidden: say what it is and who grades it how.
                macro = 'HW' if key in WEAK else 'H'
                note = clean(x.get('note', ''))
                arg = ''
                if key not in seen:
                    seen[key] = s
                    arg = '|' + s
                h.append(f"- Graders differ ({clean(x['grader'])}): {s}"
                         + (f" {note}" if note else '') + f" ({{{macro} {key}{arg}}})")
                continue
            if key not in seen:
                seen[key] = s
                h.append(f"- {{HS {key}|{s}}}")
            else:
                h.append(f"- {s} ({{H {key}}})")
        if h:
            parts.append('In the hadith:\n' + '\n'.join(h))
        sch = []
        for x in d.get('scholarly', []):
            w = WORKS.get(x['work'], clean(x['work']))
            sch.append(f"- {clean(x['author'])}, {w}, {clean(x['locator'])}: {clean(x['summary'])}")
        if sch:
            parts.append('What the scholars say:\n' + '\n'.join(sch))
        dif = []
        for x in d.get('differences', []):
            views = '; '.join(f"{clean(v['who'])}: {clean(v['view'])}" for v in x['views'])
            note = f" {clean(x['note'])}" if x.get('note') else ''
            dif.append(f"- {clean(x['question'])} {views}.{note}")
        if dif:
            parts.append('Where scholars differ:\n' + '\n'.join(dif))
        parts.append('The story itself, chapter by chapter, is in Stories.')
        text = '\n\n'.join(parts)
        out.append(f"E('layer-{sub}',")
        out.append(f"  m={json.dumps(patterns(sub), ensure_ascii=False)},")
        out.append(f"  topic={json.dumps(title, ensure_ascii=False)},")
        out.append("  go=['/stories'],")
        out.append('  text="""\n' + text + '\n""",')
        out.append("  review='Scholar review needed: built from the app\\'s story layer (checked "
                   + d['checked'] + "); scholars to confirm the selection and wording.')")
        out.append('')
    open('tool/hadi_core/spec_96_knowledge_pack_k_layers.py', 'w', encoding='utf8').write('\n'.join(out))
    print('ok', len(ORDER))


main()
