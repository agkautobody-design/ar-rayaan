/// The ISO code for a country name someone typed or the device reported,
/// or null when nothing matches. Case-insensitive; aliases included.
String? countryCodeForName(String name) {
  final String n = name.trim().toLowerCase();
  if (n.isEmpty) return null;
  final String? alias = _countryAliases[n];
  if (alias != null) return alias;
  for (final MapEntry<String, String> e in kCountries.entries) {
    if (e.value.toLowerCase() == n) return e.key;
  }
  return null;
}
