/// The visible review line that ends every translated support card.
String crisisReviewLine(String lang) =>
    translatePhrase('Native-speaker review needed', lang);

/// The translated card for [kind] in [lang] with [lines] (the plain-text help
/// lines from HelpResources) in place; null when there is no wording, so the
/// caller shows the English card.
String? crisisCardIn(CrisisKind kind, String lang, String lines) {
  final String? t = _cards[kind]?[lang];
  if (t == null) return null;
  return '${t.replaceAll('{quran}', _quran3953[lang] ?? '').replaceAll('{lines}', lines)}\n\n${crisisReviewLine(lang)}';
}

/// The translated follow-up for [kind], or null.
String? crisisFollowUpIn(CrisisKind kind, String lang) {
  final String? t = _followUps[kind]?[lang];
  return t == null ? null : '$t\n\n${crisisReviewLine(lang)}';
}

/// The "which country" note in [lang]. [region] is the country's name as
/// written on its own help-line rows; null when no covered country is known.
/// [hasLocalForKind] is false when a country is known but the lines shown are
/// the worldwide ones because no line of this kind is saved for it.
String? crisisRegionNoteIn(
  String lang, {
  required String? region,
  required bool picked,
  required bool hasLocalForKind,
}) {
  if (!kCrisisLanguages.contains(lang)) return null;
  if (region == null) return _regionNone[lang];
  if (!hasLocalForKind) return _regionNoKind[lang]!.replaceAll('{region}', region);
  return (picked ? _regionPicked : _regionDevice)[lang]!
      .replaceAll('{region}', region);
}

